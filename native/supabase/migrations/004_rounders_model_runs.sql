-- Daily immutable-ish snapshots of research model quality, server-controlled.
create table if not exists public.rounders_model_runs (
  id bigint generated by default as identity primary key,
  sport text not null check (sport in ('NBA','NFL','NHL','MLB')),
  model_version text not null check (length(model_version) between 1 and 80),
  run_day date not null default current_date,
  as_of timestamptz not null,
  data_source text not null,
  training_games integer not null check (training_games >= 0),
  evaluated_games integer not null check (evaluated_games >= 0),
  model_mae double precision check (model_mae is null or model_mae >= 0),
  baseline_mae double precision check (baseline_mae is null or baseline_mae >= 0),
  beats_baseline boolean,
  created_at timestamptz not null default now(),
  unique (sport,model_version,run_day)
);
create index if not exists rounders_model_runs_latest
  on public.rounders_model_runs(sport,created_at desc);
alter table public.rounders_model_runs enable row level security;
revoke all on table public.rounders_model_runs from anon, authenticated;
grant select, insert, update on public.rounders_model_runs to service_role;
grant usage, select on sequence public.rounders_model_runs_id_seq to service_role;
