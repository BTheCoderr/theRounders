-- Model comparison scorecards. No anonymous/regular-user table access.
create table if not exists public.rounders_model_comparisons (
 id bigint generated by default as identity primary key,
 sport text not null check (sport in ('NBA','NFL','NHL','MLB')),
 method text not null check (method='weekly-expanding-origin-v1'),
 run_day date not null default current_date,
 data_source text not null,
 data_state text not null check (data_state in ('external','simulated')),
 historical_games integer not null check (historical_games>=0),
 evaluated_games integer not null check (evaluated_games>=0),
 evaluated_weeks integer not null check (evaluated_weeks>=0),
 seasons jsonb not null default '[]'::jsonb check (jsonb_typeof(seasons)='array'),
 metrics jsonb not null default '[]'::jsonb check (jsonb_typeof(metrics)='array'),
 best_model text,
 beats_baseline boolean,
 warning text not null,
 created_at timestamptz not null default now(),
 unique(sport,method,run_day)
);
create index if not exists rounders_model_comparisons_sport_date
 on public.rounders_model_comparisons(sport,run_day desc);
alter table public.rounders_model_comparisons enable row level security;
revoke all on table public.rounders_model_comparisons from anon, authenticated;
grant select,insert,update on table public.rounders_model_comparisons to service_role;
grant usage,select on sequence public.rounders_model_comparisons_id_seq to service_role;
