-- Rounders research warehouse. All writes are server-only.
-- Do not grant public data API access. RLS is defense in depth.
create table if not exists public.rounders_games (
  id bigint generated by default as identity primary key,
  source text not null check (source in ('espn-scoreboard')),
  source_event_id text not null,
  sport text not null check (sport in ('NBA','NFL','NHL','MLB')),
  season integer not null check (season between 1900 and 2200),
  occurred_at timestamptz not null,
  home text not null check (length(home) between 1 and 100),
  away text not null check (length(away) between 1 and 100),
  home_score integer not null check (home_score >= 0),
  away_score integer not null check (away_score >= 0),
  neutral boolean not null default false,
  ingested_at timestamptz not null default now(),
  unique(source,sport,source_event_id),
  constraint rounders_different_teams check (home <> away)
);
create index if not exists rounders_games_sport_date_idx
  on public.rounders_games(sport, occurred_at desc);
alter table public.rounders_games enable row level security;
revoke all on table public.rounders_games from anon, authenticated;
grant select, insert, update on public.rounders_games to service_role;
grant usage, select on sequence public.rounders_games_id_seq to service_role;

create table if not exists public.rounders_ingestion_runs (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  sport text not null check (sport in ('NBA','NFL','NHL','MLB')),
  source text not null,
  games_seen integer not null check (games_seen >= 0),
  status text not null check (status in ('ok','error')),
  detail text not null default ''
);
alter table public.rounders_ingestion_runs enable row level security;
revoke all on table public.rounders_ingestion_runs from anon, authenticated;
grant select, insert on public.rounders_ingestion_runs to service_role;
grant usage, select on sequence public.rounders_ingestion_runs_id_seq to service_role;

-- Atomic shared quota for billable LLM requests; independent of serverless instance memory.
create table if not exists public.rounders_ai_quota (
  quota_scope text not null check (quota_scope in ('global_day','identity_window')),
  window_start timestamptz not null,
  identifier text not null,
  requests integer not null check (requests >= 0),
  primary key (quota_scope, window_start, identifier)
);
alter table public.rounders_ai_quota enable row level security;
revoke all on table public.rounders_ai_quota from anon, authenticated;
grant select, insert, update, delete on public.rounders_ai_quota to service_role;

create or replace function public.rounders_claim_ai_quota(p_identity text)
returns boolean
language plpgsql volatile security invoker
set search_path = ''
as $$
declare
  v_day timestamptz := date_trunc('day', now() at time zone 'UTC') at time zone 'UTC';
  v_15m timestamptz := date_trunc('hour', now()) +
    (floor(extract(minute from now())/15) * interval '15 minutes');
  v_global integer;
  v_identity integer;
begin
  if p_identity is null or length(p_identity) <> 64 or p_identity !~ '^[a-f0-9]{64}$' then
    return false;
  end if;
  -- Global transaction mutex protects the check and both increments across instances.
  perform pg_catalog.pg_advisory_xact_lock(83219104, 15);
  select requests into v_global from public.rounders_ai_quota
    where quota_scope = 'global_day' and window_start = v_day and identifier = 'all';
  select requests into v_identity from public.rounders_ai_quota
    where quota_scope = 'identity_window' and window_start = v_15m and identifier = p_identity;
  if coalesce(v_global,0) >= 100 or coalesce(v_identity,0) >= 8 then
    return false;
  end if;
  insert into public.rounders_ai_quota(quota_scope,window_start,identifier,requests)
    values ('global_day',v_day,'all',1)
    on conflict(quota_scope,window_start,identifier) do update
      set requests = public.rounders_ai_quota.requests+1;
  insert into public.rounders_ai_quota(quota_scope,window_start,identifier,requests)
    values ('identity_window',v_15m,p_identity,1)
    on conflict(quota_scope,window_start,identifier) do update
      set requests = public.rounders_ai_quota.requests+1;
  return true;
end;
$$;
revoke all on function public.rounders_claim_ai_quota(text) from public, anon, authenticated;
grant execute on function public.rounders_claim_ai_quota(text) to service_role;
