-- Immutable, timestamped pregame predictions and their grading. Server-only access.
-- A prediction row is written once (first snapshot wins) and may only be graded afterwards.
create table if not exists public.rounders_predictions (
  id bigint generated by default as identity primary key,
  sport text not null check (sport in ('NBA','NFL')),
  provider text not null check (provider = 'espn'),
  provider_event_id text not null check (provider_event_id ~ '^[0-9]{1,20}$'),
  season integer not null check (season between 1900 and 2200),
  starts_at timestamptz not null,
  home text not null check (length(home) between 1 and 100),
  away text not null check (length(away) between 1 and 100),
  home_team_id text not null,
  away_team_id text not null,
  neutral boolean not null default false,
  model_id text not null check (model_id in ('rounders-v1','power-v2','rpi-v2.1')),
  model_version text not null check (length(model_version) between 1 and 80),
  totals_model text not null check (length(totals_model) between 1 and 40),
  predicted_at timestamptz not null,
  projected_home double precision not null,
  projected_away double precision not null,
  projected_margin double precision not null,
  projected_total double precision not null check (projected_total >= 0),
  home_win_probability double precision not null check (home_win_probability > 0 and home_win_probability < 1),
  projected_winner text not null,
  training_games integer not null check (training_games >= 0),
  training_through timestamptz,
  data_source text not null,
  -- Pregame market line captured with the snapshot, only from a live provider; null otherwise.
  market_spread_home double precision,
  market_total double precision,
  market_source text,
  -- Grading
  grade_status text not null default 'pending' check (grade_status in ('pending','graded','void')),
  final_home integer check (final_home >= 0),
  final_away integer check (final_away >= 0),
  winner_correct boolean,
  brier double precision check (brier is null or (brier >= 0 and brier <= 1)),
  margin_error double precision,
  total_error double precision,
  graded_at timestamptz,
  created_at timestamptz not null default now(),
  constraint rounders_predictions_pregame check (predicted_at < starts_at),
  constraint rounders_predictions_training_past check (training_through is null or training_through < predicted_at),
  constraint rounders_predictions_graded_complete check (
    grade_status <> 'graded' or (final_home is not null and final_away is not null and graded_at is not null and graded_at > starts_at)),
  unique (sport, provider, provider_event_id, model_version)
);
create index if not exists rounders_predictions_upcoming on public.rounders_predictions (sport, starts_at);
create index if not exists rounders_predictions_pending on public.rounders_predictions (grade_status, starts_at) where grade_status = 'pending';
create index if not exists rounders_predictions_model on public.rounders_predictions (sport, model_id, grade_status, starts_at desc);
alter table public.rounders_predictions enable row level security;
revoke all on table public.rounders_predictions from anon, authenticated;
grant select, insert, update on public.rounders_predictions to service_role;
grant usage, select on sequence public.rounders_predictions_id_seq to service_role;

-- Prediction content is frozen: only grading columns may change after insert.
create or replace function public.rounders_predictions_freeze()
returns trigger language plpgsql set search_path = '' as $$
begin
  if (new.sport, new.provider_event_id, new.model_id, new.model_version, new.predicted_at, new.starts_at,
      new.projected_home, new.projected_away, new.projected_margin, new.projected_total,
      new.home_win_probability, new.projected_winner, new.market_spread_home, new.market_total)
     is distinct from
     (old.sport, old.provider_event_id, old.model_id, old.model_version, old.predicted_at, old.starts_at,
      old.projected_home, old.projected_away, old.projected_margin, old.projected_total,
      old.home_win_probability, old.projected_winner, old.market_spread_home, old.market_total) then
    raise exception 'rounders_predictions rows are immutable; only grading columns may change';
  end if;
  return new;
end $$;
drop trigger if exists rounders_predictions_freeze on public.rounders_predictions;
create trigger rounders_predictions_freeze before update on public.rounders_predictions
  for each row execute function public.rounders_predictions_freeze();

-- Daily walk-forward backtests and promotion-gate decisions.
create table if not exists public.rounders_backtests (
  id bigint generated by default as identity primary key,
  sport text not null check (sport in ('NBA','NFL')),
  engine_revision text not null,
  run_day date not null default current_date,
  data_source text not null,
  champion text not null,
  historical_games integer not null check (historical_games >= 0),
  evaluated_games integer not null check (evaluated_games >= 0),
  evaluated_weeks integer not null check (evaluated_weeks >= 0),
  seasons jsonb not null default '[]'::jsonb check (jsonb_typeof(seasons) = 'array'),
  from_game timestamptz,
  through_game timestamptz,
  models jsonb not null check (jsonb_typeof(models) = 'array'),
  totals jsonb not null,
  promotion jsonb not null check (jsonb_typeof(promotion) = 'array'),
  created_at timestamptz not null default now(),
  unique (sport, engine_revision, run_day)
);
alter table public.rounders_backtests enable row level security;
revoke all on table public.rounders_backtests from anon, authenticated;
grant select, insert, update on public.rounders_backtests to service_role;
grant usage, select on sequence public.rounders_backtests_id_seq to service_role;
